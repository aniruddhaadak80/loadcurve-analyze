export type StudySource = 'computed' | 'recorded'

export interface StudyPayload {
  readonly result: StudyResult
  readonly source: StudySource
  readonly note: string
}

/**
 * The study this app renders.
 *
 * Always the recorded run. There is no live path here by design: an `EngineClient` call in this
 * process would fail on Vercel (no Python) and would duplicate the contract the CLI already
 * owns. The file is regenerated by `node scripts/record-study.mjs`, which runs the real engine.
 */
export function getStudy(): StudyPayload {
  return {
    result: recordedStudy(),
    source: 'recorded',
    note: 'Recorded engine run. Run `loadcurve verify example` locally for a live result.',
  }
}

function recordedStudy(): StudyResult {
  const path = join(process.cwd(), 'lib', 'recorded-study.json')
  return JSON.parse(readFileSync(path, 'utf8')) as StudyResult
}

function packageVersion(): string {
  try {
    const raw = readFileSync(join(process.cwd(), 'package.json'), 'utf8')
    const parsed = JSON.parse(raw) as { version?: string }
    return parsed.version ?? '0.0.0'
  } catch {
    return '0.0.0'
  }
}

export function resolveVersion(): string {
  return packageVersion()
}
