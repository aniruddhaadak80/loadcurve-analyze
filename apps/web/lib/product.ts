/**
 * The product's data layer.
 *
 * Every page reads through here — never a `fetch` in a component — so there is one place that
 * knows how a study is obtained and one set of types for it.
 *
 * **The deployed app never computes a study.** `apps/web` is a standalone Vercel project: the
 * engine is a Python subprocess and Vercel has no interpreter, so there is nothing to run. The
 * page therefore renders `lib/recorded-study.json`, which is produced by the real engine via
 * `scripts/record-study.mjs` and asserted against the real response schema by a test in
 * `packages/engine-model`. `source` is part of the payload so the page can say which it is
 * showing, and a reader is never left believing a recorded number was computed for them.
 *
 * See [ADR-0003](../../../docs/adr/0003-web-app-self-contained.md).
 */
